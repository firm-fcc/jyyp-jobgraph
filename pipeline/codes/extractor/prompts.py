# 技能分类提示词：判断每个子句涉及哪些技能（1:n），并提取技能点（仅限工具/框架/语言等具体技术实体）
PROMPT_SKILL = """你是岗位技能标注器。给定技能体系标签，判断招聘JD的每个子句涉及哪些技能，并从句子中提取**技能点**。
技能体系：
{labels}

**技能点定义**：技能点 = 句子中出现的**具体技术实体**，例如：
- 编程语言：Python、Java、C++、Go、JavaScript、SQL
- 框架/库：Spring Cloud、PyTorch、TensorFlow、LangChain、Vue、React
- 工具/平台：Docker、Kubernetes、Git、Jenkins、Kafka、Linux、AWS
- 数据库/中间件：MySQL、Redis、PostgreSQL、MongoDB、Hadoop、Spark
- 其他具体技术：RAG、Transformer、微服务、分布式

**反例（不算技能点）**：工作活动、能力描述、抽象概念——如"软件测试""系统设计""问题解决""架构选型""品质异常处理""性能优化""团队协作"等。这类内容不得作为技能点输出。

规则：
- 每个子句可命中 0 个、1 个或多个技能（1:n）。
- 每个命中的技能，列出该句中对应的技能点（**原词**，不归一化）。若该技能在句中无具体技术实体，skillpoints 留空数组。
- 软技能（code 以 F 开头）通常没有技能点，skillpoints 留空数组。
- 只依据子句原文判断，不要过度推断。
- 若子句不含任何技能，skills 为空数组。

严格只输出 JSON 数组，不要任何其他文字，格式：
[{"sentence":"原句子","skills":[{"code":"T-SW-01","name":"通用程序设计与软件工程","skillpoints":["Java","Spring Cloud"]}]}, ...]

待分类子句：
{sentences}"""

# 任务分类提示词：判断每个子句涉及哪些任务（1:n）
PROMPT_TASK = """你是岗位任务标注器。给定任务体系标签，判断招聘JD的每个子句涉及哪些工作任务。
任务体系：
{labels}

规则：
- 每个子句可命中 0 个、1 个或多个任务（1:n）。
- 只依据子句原文判断，不要过度推断。
- 若子句不含任何任务，tasks 为空数组。

严格只输出 JSON 数组，不要任何其他文字，格式：
[{"sentence":"原句子","tasks":[{"code":"T-01","name":"大模型应用开发与集成"}]}, ...]

待分类子句：
{sentences}"""


def get_prompt(mode):
    if mode == "skill":
        return PROMPT_SKILL
    if mode == "task":
        return PROMPT_TASK
    raise ValueError(f"未知 mode: {mode}")


