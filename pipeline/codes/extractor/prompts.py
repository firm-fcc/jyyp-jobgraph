# 叠层确证复核门（2026-08-30）：句级/标题级分类命中在落 require 证据前的第二道
# 独立守门。根因实证：混批上下文+采样使同句判定漂移（5 次重复试验假阳性句中 1 次，
# 干净批 0 次）——与论文通道 recheck_keeps 同型问题，同型解法：独立复核、宁严勿宽。
PROMPT_OVERLAY_RECHECK = """你是叠层确证的守门员。以下 (叠层实体, 证据句) 对来自 JD 句级/标题级分类的命中，
但分类在批量上下文与采样下存在判定漂移（领域词联想导致的松命中）。请独立复核：该句的
**核心活动/核心称谓**是否与实体定义的核心动作真正吻合。

判定规则（宁严勿宽）：
- 吻合 = 句子核心就是定义所述活动（如"生成合成训练数据扩充训练集" ↔ 仿真数据增强）；
- **不吻合** = 仅共享领域词或仅同属一个大领域（"仿真测试/仿真验证"不是数据增强；
  "数据治理/数据质量"不是分布漂移治理；"知识图谱研究背景"不是嵌入质量评估；
  "高性能计算开发"不必然是科研软件工程——须句中有科研场景证据）；
- 标题级证据（"JD标题：…｜正文信号：…"）：领域定位分层——通用多义头衔（产品工程师等）
  须正文信号与画像领域一致，仅字面对应不通过；头衔含行业专名（航天/联试/量子等）则头衔
  即定位领域、信号只需不矛盾（信号经体系映射后常只剩通用词，不构成否决）；职责对应仍须成立；
- 无法确定 → pass=false（宁缺毋滥）。

严格只输出 JSON 数组，无其他文字，格式：
[{"idx": 0, "pass": true, "reason": "核心活动吻合：..."}, ...]

待复核对：
{pairs}"""


def format_prompt(mode, labels_text, sentences):
    """组装完整提示词。sentences: list[str]"""
    tmpl = get_prompt(mode)
    import json
    return tmpl.replace("{labels}", labels_text) \
               .replace("{sentences}", json.dumps(sentences, ensure_ascii=False))
