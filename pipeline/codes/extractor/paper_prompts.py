def get_paper_prompt(mode):
    """按模式返回论文提及分类提示词。mode: skill | task | job"""
    if mode == "skill":
        return PROMPT_PAPER_SKILL
    if mode == "task":
        return PROMPT_PAPER_TASK
    if mode == "job":
        return PROMPT_PAPER_JOB
    raise ValueError(f"未知 mode: {mode}（应为 skill / task / job）")
