"""岗位热更新提示词模板（新岗位 → 任务/技能关联分析 + 关联候选体系映射）。

设计原则（与论文/新闻提示词一致，历史反馈沉淀）：
- **不硬编码数量配额**："0 条或任意条，宁缺毋滥"——配额会被模型当任务填满
- **仅显式信号**：只从岗位提及文本中提取被**明确支撑**的任务/技能，禁止推断
- **粒度契约**：任务=抽象工作类别（非岗位名/工具/算法名）；技能=稳定能力类别
  （单一工具/框架/语言 → 技能点层，本模块不提取）
- **定义与证据必填**：name_zh/name_en + definition（它是什么）+ evidence（逐字原文）
- evidence 必须来自提供的提及文本，禁止编造

本文件为**唯一命名**模块（builder 自持），供 job_hot_update 使用；
taxonomy_mapper 的映射复用经 `prompt_template` 参数传入 PROMPT_JOB_MAP。
"""

# ---------------- 新岗位 → 任务/技能关联分析（Stage A） ----------------
PROMPT_JOB_ASSOC = """你是岗位能力图谱的"岗位-任务-技能"关联分析员。给定一个**新岗位**及其提及文本（论文/新闻中明确提及该岗位的原文句），从中抽取该岗位的**核心工作任务**与**所需技能**，供图谱把新岗位关联到任务/技能体系。

输入：
新岗位：{name_zh}（{name_en}）
定义：{definition}
提及文本（原文句，按来源文档聚合，[doc_id] 开头）：
{evidence_text}

请输出两部分：

一、tasks：该岗位涉及的核心**工作任务类别**。任务是抽象的"活儿"（如"多源数据可信度评估与治理"），可被多个岗位执行。**不是**岗位名、**不是**技术栈名、**不是**算法名。
二、skills：该岗位所需的**稳定能力类别**（如"生成式AI系统评估"）。**单一工具/框架/语言/模型名**（如 PyTorch、Java、RAG）不是技能（归技能点层），不要输出为 skills。

每条（tasks 与 skills 均适用）：
- name_zh: 中文名（语境化翻译，脱离上下文可理解；**简洁自足**——通常 4-12 个汉字、上限 14；优先「动作+对象」或「限定+核心」结构，避免堆砌"的/与/及"、避免重复词）
- name_en: 英文原名（提及文本中出现则保留；无则空字符串）
- definition: 定义——"它是什么"，1-2 句，让读者脱离文本也能理解
- evidence: 原文句数组（**必须逐字引用**上面的提及文本，禁止编造）
- confidence: high | medium | low

严格要求：
- **只抽取被提及文本明确支撑**的任务/技能；禁止推断、禁止脑补。
- 每条必须同时含 definition 与 evidence；缺一不可，否则不要输出该条。
- 宁缺毋滥：文本不足以支撑任何任务/技能 → 对应数组为空。
- 不硬编码数量。

输出 JSON 对象，格式：
{
  "tasks": [
    {"name_zh": "...", "name_en": "...", "definition": "...", "evidence": ["原文句..."], "confidence": "high"}
  ],
  "skills": [
    {"name_zh": "...", "name_en": "...", "definition": "...", "evidence": ["原文句..."], "confidence": "high"}
  ]
}
仅输出该 JSON 对象。"""


# ---------------- 关联候选体系映射（Stage B，job_hot_update 专用） ----------------
PROMPT_JOB_MAP = """你是一名岗位能力图谱体系映射监督员。你的职责是把**从新岗位提及文本中提取的任务/技能候选**映射到已有体系，决定每条候选应该：映射到基础体系已有条目（视为已覆盖）、合并到增量层已有条目（跨岗位/跨来源同一信号）、保持为新条目（keep）、或拒绝（噪声/粒度不符）。

输入三部分：

一、基础体系标签（候选语义与之充分接近即视为已覆盖）：
【任务体系】{task_labels}
【技能体系】{skill_labels}
【岗位体系】{job_labels}

二、当前增量层（ΔG）已有候选条目（跨岗位合并目标）：
{delta_labels}

三、本次候选批（JSON 数组，index 从 0 开始）：
{candidates}

映射规则（按优先级）：
1. **映射先行**：候选语义充分接近基础体系某条目 → status=keep 且 map_to 填 {taxonomy, code}。名称不必完全一致，语义覆盖即算已覆盖。
2. **下位概念视为已覆盖**：候选是某基础条目的更具体子概念 → map_to 该基础条目。
3. **跨岗位合并**：候选与增量层已有条目语义等价（同一任务/技能被多个岗位支持 = 更强信号，不是多条）→ merge_into 填已有条目 id。
4. **粒度审查（拒绝）**：
   - 任务类候选若是岗位名、技术栈名、算法名、产品名 → status=reject，reject_reason 注明"岗位名/技术栈/算法名，非抽象任务类别"。
   - 技能类候选若是单一工具/框架/语言/模型名 → status=reject，reject_reason 注明"单一工具/框架/语言，应归技能点层而非技能"。
5. **keep（新条目）仅当**：完全无法映射 + 属于新的大类任务类别/稳定能力类别 + 增量层也无等价条目。keep 极端保守，宁缺毋滥。

对每条候选输出一个 decision（index 对应候选序号），最终 kind 可修正。命名：**name_zh 归一化为简洁规范名**（通常 4-12 个汉字、上限 14，避免堆砌"的/与/及"、避免重复词，风格与上方体系一致），name_en 保留英文原名：
{
  "decisions": [
    {
      "index": 0,
      "final_kind": "new_task" | "new_skill",
      "name_zh": "归一化后的中文名（可理解、语境化）",
      "name_en": "保留英文原名",
      "status": "keep" | "reject",
      "map_to": null | {"taxonomy": "tasks" | "skills" | "jobs", "code": "T-07"},
      "merge_into": null | "PT-001",
      "reject_reason": "仅 status=reject 时填写",
      "reason": "裁决依据（一句话）"
    }
  ]
}
仅输出该 JSON 对象。"""
