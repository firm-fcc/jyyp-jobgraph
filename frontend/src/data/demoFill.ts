/* 词条编译成正则：纯 ASCII 的词条按词边界匹配，含中文的按包含匹配。
   不加词边界的话 UX 会命中 Linux、SoC 会命中 Socket、UI 会命中 EasyUI ——
   十几个后端岗位会因此被判成做 UI/UX 设计。 */
const KW_RE: [string, RegExp][] = Object.entries(TASK_KEYWORDS).map(([task, words]) => [
  task,
  new RegExp(
    words
      .map((w) => {
        const esc = w.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
        return /^[\x20-\x7e]+$/.test(w) ? `(?<![A-Za-z0-9])${esc}(?![A-Za-z0-9])` : esc;
      })
      .join('|'),
    'i',
  ),
]);

/** 一个岗位的关键词落在哪几项任务上，按命中条数从多到少 */
function tasksByKeyword(keywords: string[]): string[] {
  const hit = new Map<string, number>();
  for (const k of keywords) {
    for (const [task, re] of KW_RE) {
      if (re.test(k)) hit.set(task, (hit.get(task) ?? 0) + 1);
    }
  }
  return [...hit.entries()].sort((a, b) => b[1] - a[1]).map(([t]) => t);
}

/** 一项任务需要哪些能力组。表里没有的任务退到兜底画像的必备能力上 */
export function demoTaskSkills(taskName: string): string[] {
  return TASK_SKILL_MAP[taskName] ?? FALLBACK_PROFILE.must;
}

/**
 * 一个岗位的能力与任务画像。
 *
 * 任务 = 类别骨架的两项 + 本岗位关键词命中最多的两项（去重后至多四项）。
 * 关键词一条都没命中时（岗位词表偏业务、不落任何技术词面），退回类别自己的
 * 备选池按编码哈希取一项 —— 池子是类别自己的 flexTasks，不是全库随机：
 * 全库随机的写法在单个岗位上看不出问题，聚合到类别就塌了，一个类别几十个
 * 岗位各摸一项，并集必然是全部 27 项任务，"按类别看能力要求"直接失效。
 *
 * 能力 = 类别必备 + 这些任务各自要求的能力组（走 TASK_SKILL_MAP）。
 * 由任务反推能力，而不是给岗位另开一张能力表：一个岗位要什么能力，
 * 本来就该由它做什么事决定，两张表各写一遍只会对不上。
 */
export function demoJobProfile(
  key: string,
  category: string,
  keywords: string[] = [],
): { must: string[]; plus: string[]; tasks: string[] } {
  const p = DEMO_CATEGORY_PROFILE[category] ?? FALLBACK_PROFILE;

  /* 关键词命中主导，类别骨架只作兜底。
     反过来（骨架打底、关键词加两项）试过，任务段会塌成两根长条加一列碴儿：
     骨架那两项被全类几十个岗位共同持有，要求强度是其余任务的五到三十倍，
     标尺被它们拉满之后，靠关键词分出来的那些任务在图上只剩几个像素。
     岗位真正做什么事，它自己的关键词比它所属的类别更有发言权。 */
  const byKw = tasksByKeyword(keywords);
  const tasks = [...byKw, ...p.tasks.filter((t) => !byKw.includes(t))].slice(0, 3);
  if (tasks.length < 3 && p.flexTasks.length) {
    const c = p.flexTasks[randInt(`${key}|task`, 0, p.flexTasks.length - 1)];
    if (c && !tasks.includes(c)) tasks.push(c);
  }

  /* 能力：类别必备打底，再并上这些任务要求的能力组。
     并集按出现次数排序 —— 被两项任务同时要求的能力组，在这个岗位上确实更吃重。 */
  const freq = new Map<string, number>();
  for (const s of p.must) freq.set(s, (freq.get(s) ?? 0) + 2);
  for (const t of tasks) for (const s of TASK_SKILL_MAP[t] ?? []) freq.set(s, (freq.get(s) ?? 0) + 1);
  const ranked = [...freq.entries()].sort((a, b) => b[1] - a[1]).map(([s]) => s);

  const must = ranked.slice(0, Math.max(2, Math.min(3, ranked.length)));
  const plus = [...p.plus, ...ranked.slice(must.length)].filter(
    (s, i, a) => !must.includes(s) && a.indexOf(s) === i,
  );
  return { must, plus, tasks };
}

