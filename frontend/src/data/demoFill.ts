/* ---------------- 技术名 → 技能点抽取词典 ----------------
   简历里写的是具体技术（Python、Flink、LangChain），能力体系里存的是
   技能点（程序设计与软件工程、大数据与分布式计算）。
   两者之间需要一份归并词典，算法侧尚未产出，这里按演示规模先给一份，
   让"简历解析 → 能力归并 → 差距分析"这条链路可以完整走通。

   左边是简历原文里的写法，右边是 skills0821.json 里的规范技能点名。 */
export function extractedSkillName(raw: string, isReal: boolean): string {
  return (isReal && DEMO_SKILL_EXTRACTION[raw]) || raw;
}

/**
 * 简历里的一个写法在图谱中的落点。
 *
 * 三种情形，判定顺序不可调换：
 *   其一，该写法本身就是图谱里的技能点，落点即该技能点，不归并；
 *   其二，技能点层没有它，但归并词典能把它对到某一项技能，落点为该技能；
 *   其三，两者皆不中，落点仍记作技能点，界面上如实标为未对齐。
 *
 * 简历解析与真实性核验两处必须走同一个判定，否则同一个写法会在一处对得上、
 * 另一处对不上，报告里"已对齐"与"未对齐"两栏就会互相矛盾。
 */
export function resolveClaim(raw: string): {
  id: string;
  /** 归并到的技能名。写法本身即体系内条目时不带这一项 */
  mappedName?: string;
  inSystem: boolean;
} {
  if (!IS_REAL_TAXONOMY) return { id: `SP:${raw}`, inSystem: true };
  if (IS_REAL_GRAPH && SKILLPOINT_NAMES.has(raw)) return { id: `SP:${raw}`, inSystem: true };
  const merged = DEMO_SKILL_EXTRACTION[raw];
  if (merged) {
    const code = IS_REAL_GRAPH ? SKILL_CODE_BY_NAME.get(merged) : undefined;
    return { id: code ? `S:${code}` : `SP:${merged}`, mappedName: merged, inSystem: true };
  }
  return { id: `SP:${raw}`, inSystem: false };
}

