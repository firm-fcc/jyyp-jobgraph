/* ---------------- 发现时间 ----------------
   真实分类文件没有这一维。按名称哈希确定性铺到 2019-01 ~ 2025-06 之间，
   同一个名字每次刷新落在同一个月，图上不会跳。 */

const SPREAD_FROM = 2019;
const SPREAD_MONTHS = 78; // 2019-01 起 78 个月 → 2025-06

export function demoFirstSeen(key: string): string {
  const i = randInt(`${key}|firstSeen`, 0, SPREAD_MONTHS - 1);
  const y = SPREAD_FROM + Math.floor(i / 12);
  const m = (i % 12) + 1;
  return `${y}-${String(m).padStart(2, '0')}`;
}

/* ---------------- 成熟度分档 ----------------
   真实体系没有这一维（skills0821.json 只有软硬分类，没有成熟度）。
   按首现年份分三档：越晚出现的越靠前沿，招聘市场跟进得越慢。
   这一档同时决定三源曲线的形状 —— 前沿项论文先起、招聘后跟，
   前瞻热度才有正值可看；全部压成"基础"的话整张前瞻分析恒为零。 */
export function demoLevel(firstSeen: string): 1 | 2 | 3 {
  const y = Number(firstSeen.slice(0, 4));
  return y >= 2023 ? 3 : y >= 2021 ? 2 : 1;
}

