/** 城市 → 省。直辖市与特别行政区自身也入表，使 provinceOf 对它们同样成立 */
const OF = new Map<string, string>();
for (const p of ['北京', '天津', '上海', '重庆', '香港', '澳门']) OF.set(p, p);
for (const [p, cities] of Object.entries(CITIES_BY_PROVINCE)) {
  OF.set(p, p);
  for (const c of cities) OF.set(c, p);
}

/** 表外城市，供口径核对 */
const UNMAPPED = new Set<string>();

/* place 列的写法不整齐：多数是市名，另有一部分直接写省名（“广东省”）、
   写到州或地区一级（“红河州”“喀什地区”），或带开发区后缀（“燕郊开发区”）。
   逐一入表不如先去掉这几个后缀再查一次 —— 后缀去掉之后落在表内的，
   与直接写市名的是同一个地方。 */
const SUFFIX = /(省|市|自治区|特别行政区|自治州|州|地区|盟|新区|经济开发区|开发区|工业园区)$/;

/** 一座城属于哪个省级行政区。表外的一律归“其他”并记名 */
export function provinceOf(city: string): string {
  const hit = OF.get(city);
  if (hit) return hit;
  const trimmed = city.replace(SUFFIX, '');
  if (trimmed && trimmed !== city) {
    const alt = OF.get(trimmed);
    if (alt) return alt;
  }
  if (city) UNMAPPED.add(city);
  return PROVINCE_OTHER;
}

/** 落在“其他”里的城市名，按名排序。界面上交代口径时读它 */
export const unmappedCities = () => [...UNMAPPED].sort();

/** 该省下在对照表里登记的城市。直辖市与特别行政区返回自身 */
export function citiesOf(province: string): string[] {
  if (province === PROVINCE_OTHER) return [];
  const list = CITIES_BY_PROVINCE[province];
  return list ? [province, ...list] : [province];
}
